    # ------------------------------------------------------------------
    # Item 24e: burn-in and interval default to `nothing`, resolved by the
    # ONE dyad-scaled rule of ERGM.jl applied to the swap count
    # n(n−1)(n−2)/2 — the size of the AlterSwap proposal space.
    # ------------------------------------------------------------------
    @testset "Sampler defaults scale with the ranking size" begin
        for n in (4, 6, 17)
            rnet = RankNetwork(n)
            n_swaps = n * (n - 1) * (n - 2) ÷ 2
            @test ERGMRank._n_comparisons(rnet) == n_swaps
            @test ERGMRank._mcmc_defaults(rnet) == ERGM._mcmc_defaults(n_swaps)
            @test ERGMRank._resolve_mcmc_controls(rnet, nothing, nothing) ==
                  (20 * n_swaps, max(100, n_swaps ÷ 10))
            # Explicit integers are honoured unchanged, singly or together
            @test ERGMRank._resolve_mcmc_controls(rnet, 7, nothing) == (7, max(100, n_swaps ÷ 10))
            @test ERGMRank._resolve_mcmc_controls(rnet, nothing, 9) == (20 * n_swaps, 9)
            @test ERGMRank._resolve_mcmc_controls(rnet, 7, 9) == (7, 9)
        end
        @test ERGMRank._resolve_mcmc_controls(RankNetwork(4), nothing, nothing) == (240, 100)
        @test ERGMRank._resolve_mcmc_controls(RankNetwork(17), nothing, nothing) == (40800, 204)

        # The three entry points default to `nothing`
        kw(f, sig) = Base.kwarg_decl(which(f, sig))
        @test :burnin in kw(simulate_rank_ergm,
                            (RankNetwork, Vector{AbstractERGMTerm}, Vector{Float64}))
        @test :burnin in kw(gof, (RankERGMResult,))
        @test :boot_burnin in kw(fit_ergm_rank, (RankNetwork, Vector{AbstractERGMTerm}))
        # ...and a default run is the explicit one at the resolved values
