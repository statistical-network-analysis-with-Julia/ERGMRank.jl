    # ------------------------------------------------------------------
    # Per-term swap change statistics (WP2): `swap_change(term, rnet, ego,
    # j, k)` evaluates only the comparisons the swap touches, and must equal
    # the brute-force oracle g(y_swapped) − g(y) EXACTLY — `==`, not ≈: the
    # counting terms are integers, and the covariate terms are tested with
    # integer-valued covariates so that both sides are exact in Float64.
    # ------------------------------------------------------------------
    @testset "swap_change equals the brute-force oracle exactly" begin
        function all_terms(n, rng)
            x = Float64.(rand(rng, -5:5, n))
            cov = Float64.(rand(rng, -3:3, n, n))
            ref = random_rank_network(n; rng=rng)
            return AbstractERGMTerm[RankDeference(), RankNonconformity(:all),
                                    RankNonconformity(:localAND), RankNodeICov(x),
                                    RankInconsistency(ref), RankEdgeCov(cov)]
        end

        # 200 random (network, ego, j, k) cases at each of n = 4, 5, 8
        rng = Xoshiro(2026)
        for n in (4, 5, 8)
            n_checked = 0
            for _ in 1:200
                rnet = random_rank_network(n; rng=rng)
                ego = rand(rng, 1:n)
                j = rand(rng, 1:n)
                while j == ego
                    j = rand(rng, 1:n)
                end
                k = rand(rng, 1:n)
                while k == ego || k == j
                    k = rand(rng, 1:n)
                end
                terms = all_terms(n, rng)
                before = rank_matrix(rnet)
                oracle = ERGMRank._swap_delta_bruteforce(terms, rnet, ego, j, k)
                fast = [swap_change(t, rnet, ego, j, k) for t in terms]
                fast == oracle || @error "swap_change ≠ oracle" n ego j k fast oracle
                n_checked += Int(fast == oracle)
                @test rank_matrix(rnet) == before          # rnet untouched
            end
            @test n_checked == 200
        end

        # The R-pinned 4-actor network: every (ego, j, k), every term
        rt = r_test_network()
        terms4 = AbstractERGMTerm[RankDeference(), RankNonconformity(:all),
                                  RankNonconformity(:localAND),
                                  RankNodeICov([10.0, 20.0, 30.0, 40.0]),
                                  RankInconsistency(random_rank_network(4; rng=Xoshiro(4))),
                                  RankEdgeCov(Float64.(reshape(1:16, 4, 4)))]
        n_swaps = 0
        for ego in 1:4, j in 1:4, k in 1:4
            (j == ego || k == ego || j == k) && continue
            n_swaps += 1
            oracle = ERGMRank._swap_delta_bruteforce(terms4, rt, ego, j, k)
            @test [swap_change(t, rt, ego, j, k) for t in terms4] == oracle
            # ...and the sign convention is g(swapped) − g(observed)
            swapped = copy(rt)
            swap_ranks!(swapped, ego, j, k)
            @test swap_change(RankDeference(), rt, ego, j, k) ==
                  compute(RankDeference(), swapped) - compute(RankDeference(), rt)
        end
        @test n_swaps == 4 * 3 * 2          # ordered (j, k): both orders visited
        # A swap and its reverse are the same move
        @test swap_change(RankNonconformity(), rt, 1, 2, 3) ==
              swap_change(RankNonconformity(), rt, 1, 3, 2)

        # Real-valued covariates: exact up to rounding of the oracle's
        # cancellation (the oracle subtracts two O(n³) sums)
        rnet = random_rank_network(7; rng=Xoshiro(8))
        for t in (RankNodeICov(rand(Xoshiro(9), 7)), RankEdgeCov(rand(Xoshiro(10), 7, 7)))
            @test swap_change(t, rnet, 2, 5, 6) ≈
                  ERGMRank._swap_delta_bruteforce([t], rnet, 2, 5, 6)[1] atol = 1e-12
        end

        # The swap must name an ego and two distinct alters
        @test_throws ArgumentError swap_change(RankDeference(), rt, 1, 1, 2)
        @test_throws ArgumentError swap_change(RankDeference(), rt, 1, 2, 2)
        @test_throws ArgumentError swap_change(RankDeference(), rt, 1, 2, 5)
        # ...and a covariate of the wrong size is refused as `compute` refuses it
        @test_throws ArgumentError swap_change(RankNodeICov([1.0, 2.0]), rt, 1, 2, 3)
        @test_throws ArgumentError swap_change(RankEdgeCov(zeros(2, 2)), rt, 1, 2, 3)
        @test_throws ArgumentError swap_change(RankInconsistency(zeros(Int, 2, 2)), rt, 1, 2, 3)
    end

    @testset "swap_change and _swap_delta! allocate nothing" begin
        n = 9
        rnet = random_rank_network(n; rng=Xoshiro(31))
        terms = AbstractERGMTerm[RankDeference(), RankNonconformity(:all),
                                 RankNonconformity(:localAND),
                                 RankNodeICov(collect(1.0:n)),
                                 RankInconsistency(random_rank_network(n; rng=Xoshiro(32))),
                                 RankEdgeCov(rand(Xoshiro(33), n, n))]
        # Measured inside a function so the term's type is inferred, as it is
        # in the sampler and the design builder
        term_allocs(t, r) = @allocated swap_change(t, r, 2, 4, 7)
        for t in terms
            term_allocs(t, rnet)                          # warm up
            @test term_allocs(t, rnet) == 0
        end

        # `_swap_delta!` over a term tuple: 0 bytes at p = 2 and at p = 8
        # (eight RankEdgeCovs — the generated fill has no `map` cliff)
        delta_allocs(delta, ts, r) = @allocated ERGMRank._swap_delta!(delta, ts, r, 2, 4, 7)
        for ts in (Tuple(terms[1:2]),
                   Tuple(AbstractERGMTerm[RankEdgeCov(rand(Xoshiro(i), n, n); label="c$i")
                                          for i in 1:8]))
            delta = zeros(length(ts))
            delta_allocs(delta, ts, rnet)                 # warm up
            @test delta_allocs(delta, ts, rnet) == 0
            @test delta ≈ ERGMRank._swap_delta_bruteforce(collect(ts), rnet, 2, 4, 7) atol = 1e-9
        end
        # ...and a workspace of the wrong length is refused, not written past
        @test_throws ArgumentError ERGMRank._swap_delta!(zeros(3), Tuple(terms[1:2]), rnet, 2, 4, 7)
    end

