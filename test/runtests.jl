    # ------------------------------------------------------------------
    # Finding N4: the MCMC MLE (`method=:mcmle`), the estimator of R ergm.rank,
    # on the ERGM.mcmle iteration (Hummel step, `ERGM.mcmc_convergence` tests,
    # `ERGM._mcmle_covariance` standard errors) with the AlterSwap chain as
    # the sampler and a path-sampling bridge for the log-likelihood.
    # ------------------------------------------------------------------
    @testset "MCMC MLE recovers a known coefficient" begin
        rng = Random.Xoshiro(11)
        n = 8
        x = collect(1.0:n) .- (n + 1) / 2
        term = RankNodeICov(x)
        θ_true = 0.15
        start = random_rank_network(n; rng=rng)
        data = simulate_rank_ergm(start, [term], [θ_true];
                                  n_sim=1, burnin=4000, interval=1, rng=rng)[1]

        fit = fit_ergm_rank(data, [term]; method=:mcmle, n_samples=512,
                            rng=Random.Xoshiro(3))
        @test fit isa RankERGMResult
        @test fit.method === :mcmle
        @test fit.converged
        @test fit.mcmc_convergence isa ERGM.MCMLEConvergence
        @test fit.mcmc_convergence.step_length == 1.0
        @test maximum(fit.mcmc_convergence.t_ratios) < 0.1
        @test fit.mcmc_convergence.hotelling_p > 0.05
        @test size(fit.mcmc_samples) == (512, 1)
        @test fit.bridge_rungs == 16
        # Recovery within 2 standard errors (a fixed seed, so deterministic)
        @test abs(coef(fit)[1] - θ_true) < 2 * stderror(fit)[1]
        @test stderror(fit)[1] > 0
        # The covariance carries the Monte-Carlo component on top of the
        # Fisher part, and the Fisher part is the inverse sampled covariance
        @test fit.vcov_fisher ≈ inv(cov(fit.mcmc_samples)) atol = 1e-12
        @test all(diag(fit.vcov) .>= diag(fit.vcov_fisher))
        @test isfinite(loglikelihood(fit)) && loglikelihood(fit) < 0
        @test isfinite(aic(fit)) && isfinite(bic(fit))
        @test aic(fit) == -2 * loglikelihood(fit) + 2 * dof(fit)
