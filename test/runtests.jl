    @testset "Bridge log-likelihood matches exact enumeration (n = 4)" begin
        # (3!)^4 = 1296 complete orderings: log Z is a sum we can write down
        m = [0 3 2 1;
             3 0 1 2;
             1 3 0 2;
             2 1 3 0]
        rnet = RankNetwork(m)
        x = [1.0, 2.0, 3.0, 4.0]
        term = RankNodeICov(x)
        terms = AbstractERGMTerm[term]
        obs = compute(term, rnet)

        perms(v) = length(v) == 1 ? [v] :
            [vcat(v[i], q) for i in eachindex(v) for q in perms(deleteat!(copy(v), i))]
        P = perms([1, 2, 3])
        vals = Float64[]
        for a in P, b in P, c in P, d in P
            M = zeros(Int, 4, 4)
            rows = (a, b, c, d)
            for i in 1:4
                cnt = 0
                for j in 1:4
                    i == j && continue
                    cnt += 1
                    M[i, j] = rows[i][cnt]
                end
            end
            push!(vals, compute(term, RankNetwork(M)))
        end
        @test length(vals) == 1296
        logsumexp(v) = (mx = maximum(v); mx + log(sum(exp.(v .- mx))))
        exact_loglik(θ) = θ * obs - logsumexp(θ .* vals)
        # The exact MLE: E_θ[g] = g_obs, by Newton on the enumerated model
        θ_exact = 0.0
        for _ in 1:50
            w = exp.(θ_exact .* vals); w ./= sum(w)
            m1 = sum(w .* vals); v1 = sum(w .* vals .^ 2) - m1^2
            θ_exact += (obs - m1) / v1
        end

        # log Z(0) = n·log((n−1)!) exactly, so loglik(0) = −4 log 6 with no draw
        @test ERGMRank._log_n_orderings(4) ≈ 4 * log(6) atol = 1e-14
        @test ERGMRank._log_n_orderings(4) ≈ log(1296) atol = 1e-12
        ts = Tuple(terms)
        rng0 = Random.Xoshiro(9)
        ll0 = ERGMRank._rank_bridge_loglik(rnet, ts, [0.0], [obs]; nrungs=8,
                                           n_samples=16, burnin=10, interval=1, rng=rng0)
        @test ll0 == -ERGMRank._log_n_orderings(4)
        @test ll0 ≈ -4 * log(6) atol = 1e-14
        @test rng0 == Random.Xoshiro(9)              # θ = 0 draws nothing

        fit = fit_ergm_rank(rnet, terms; method=:mcmle, n_samples=1024,
                            bridge_rungs=32, rng=Random.Xoshiro(4))
        @test fit.converged
        # The bridge against the enumerated log-likelihood at the same θ̂
        @test abs(loglikelihood(fit) - exact_loglik(coef(fit)[1])) < 0.05
        # ...and the MCMLE against the exact MLE, well inside a standard error
        @test abs(coef(fit)[1] - θ_exact) < 0.25 * stderror(fit)[1]

        @testset "Swap pseudo-likelihood ≠ likelihood, even for an ego-independent term" begin
            # RankNodeICov decomposes over egos, and each swap conditional
            # P(y | {y, y_swapped}) IS the model's two-state conditional — yet
            # the product of those conditionals is not the likelihood (the
            # comparisons within an ego's row must form a total order, so
            # they are never independent). The docs must not claim otherwise:
            # exact MLE −0.0767 (loglik −7.015) vs swap-MPLE −0.0880
            # (pseudo-loglik −8.057), a gap 300× the Newton tolerance. The
            # MCMLE `fit` above satisfies its convergence test at the
            # swap-MPLE start at this size and budget (no step taken, so it
            # equals the MPLE exactly); run to a tight threshold it moves to
            # −0.0772, 0.0005 from the exact MLE — 20× closer than the MPLE.
            mple = fit_ergm_rank(rnet, terms)
            @test mple.converged && mple.method === :mple
            @test θ_exact ≈ -0.07669 atol = 1e-4
            @test coef(mple)[1] ≈ -0.08803 atol = 1e-4
            @test abs(coef(mple)[1] - θ_exact) > 0.01
            tight = fit_ergm_rank(rnet, terms; method=:mcmle, n_samples=16384,
                                  conv_threshold=0.01, maxiter=40, bridge_rungs=0,
                                  rng=Random.Xoshiro(4))
            @test tight.converged
            @test abs(coef(tight)[1] - θ_exact) < 0.25 * stderror(tight)[1]
            @test abs(coef(tight)[1] - θ_exact) < 0.1 * abs(coef(mple)[1] - θ_exact)
            @test exact_loglik(θ_exact) ≈ -7.0154 atol = 1e-3
            @test loglikelihood(mple) ≈ -8.0572 atol = 1e-3
            @test abs(loglikelihood(mple) - exact_loglik(coef(mple)[1])) > 0.5
            @test !is_exact(mple) && objective(mple) === :pseudolikelihood
        end
        # The exact Fisher information at θ̂ against the sampled one
        w = exp.(coef(fit)[1] .* vals); w ./= sum(w)
        info = sum(w .* vals .^ 2) - sum(w .* vals)^2
        @test abs(fit.vcov_fisher[1, 1] - 1 / info) < 0.15 / info
    end

