    # must be unchanged: the Newcomb coefficients below are OUR OWN
    # estimator's values, recorded at full precision from the brute-force
    # code before the change — a regression literal, NOT an R value (the R
    # MLE is in the golden fixture and differs, see finding N4).
    # ------------------------------------------------------------------
    @testset "_rank_design is the brute-force design; swap-MPLE unchanged" begin
        g = load_golden(joinpath(@__DIR__, "fixtures", "newcomb_rank.toml"))
        n = Int(g.values["n_actors"])
        M = [Int(g.values["ranks"][i][j]) for i in 1:n, j in 1:n]
