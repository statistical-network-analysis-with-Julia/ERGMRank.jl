    # WP4 (panel items 4/13): the `Network` → `RankNetwork` adapter honours
    # the conversion contract — preserve what a RankNetwork can hold, reject
    # what it cannot (undirected, two-mode, masked, incomplete), report the
    # rest (`report=true` → ConversionReport). This testset is what the
    # `Network`→`RankNetwork` column of Networks.jl's
    # docs/src/guide/conversion_invariants.md cites.
    # ------------------------------------------------------------------
    @testset "Network → RankNetwork adapter honours the conversion contract" begin
        # A directed 5-actor Network whose :rank arcs carry a complete ranking
        ref = random_rank_network(5; rng=MersenneTwister(7))
        function rank_network_from(ref; attr=:rank, loops=false)
            net = network(ref.n; loops=loops)
            for i in 1:ref.n, j in 1:ref.n
                i == j && continue
                add_edge!(net, i, j)
                set_edge_attribute!(net, attr, i, j, ref.ranks[i, j])
            end
            return net
        end
        net = rank_network_from(ref)

        # Preserved: the ranks round-trip exactly, and the result is a fresh copy
        rnet = as_rank_network(net)
        @test rnet isa RankNetwork
        @test rank_matrix(rnet) == rank_matrix(ref)
        @test is_valid_ranking(rnet)
        @test compute(RankDeference(), rnet) == compute(RankDeference(), ref)
        # Lossless when :rank is the only attribute
        rnet2, rep = as_rank_network(net; report=true)
        @test rep isa ConversionReport
        @test rep.source === :Network && rep.target === :RankNetwork
        @test is_lossless(rep)
        @test isempty(dropped_fields(rep))
        @test rank_matrix(rnet2) == rank_matrix(ref)

        # Reported: every other edge attribute, every vertex attribute, every
        # network attribute — named, with a reason
        set_edge_attribute!(net, :weight, 1, 2, 2.5)
        set_vertex_attribute!(net, :sex, ["m", "f", "m", "f", "m"])
        set_vertex_attribute!(net, :age, [20, 30, 40, 50, 60])
        set_network_attribute!(net, :title, "week 1")
        rnet3, rep3 = as_rank_network(net; report=true)
        @test rank_matrix(rnet3) == rank_matrix(ref)
        @test !is_lossless(rep3)
        @test Set(dropped_fields(rep3)) == Set([:weight, :sex, :age, :title])
        @test !(:rank in dropped_fields(rep3))
        reasons = Dict(rep3.dropped)
        @test occursin("edge attribute", reasons[:weight])
        @test occursin("vertex attribute", reasons[:sex])
        @test occursin("network attribute", reasons[:title])
        @test occursin("4 dropped", sprint(show, rep3))
        # `report=false` returns the RankNetwork alone
        @test as_rank_network(net) isa RankNetwork

        # A different attribute name
        net_score = rank_network_from(ref; attr=:score)
        @test rank_matrix(as_rank_network(net_score; attr=:score)) == rank_matrix(ref)
        err = try as_rank_network(net_score); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin(":rank", err.msg) && occursin("ego 1", err.msg) && occursin(":score", err.msg)

        # Self-loop arcs have no rank: ignored, and reported
        net_loops = rank_network_from(ref; loops=true)
        add_edge!(net_loops, 2, 2)
        rl, repl = as_rank_network(net_loops; report=true)
        @test rank_matrix(rl) == rank_matrix(ref)
        @test :self_loops in dropped_fields(repl)

        # Rejected: a masked dyad is unobserved, not absent — the missing-data
        # contract, and there is no :face to offer
        @test supports_missing(as_rank_network)
        @test missing_policies(as_rank_network) == (:error,)
        masked = rank_network_from(ref)
        set_missing_dyad!(masked, 1, 2)
        err = try as_rank_network(masked); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin("as_rank_network", err.msg)
        @test occursin("masked", err.msg)
        @test !occursin("missing=:face", err.msg)     # a policy that does not exist is not advertised
        err = try as_rank_network(masked; missing=:face); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin("not offered", err.msg) && occursin("no face value", err.msg)
        err = try as_rank_network(masked; missing=:bogus); nothing catch e; e end
        @test err isa ArgumentError && occursin("not offered", err.msg)
        clear_missing_dyads!(masked)
        @test rank_matrix(as_rank_network(masked)) == rank_matrix(ref)

        # Rejected: undirected (rankings are ego-specific) and two-mode
        undirected = network(5; directed=false)
        err = try as_rank_network(undirected); nothing catch e; e end
        @test err isa ArgumentError && occursin("undirected", err.msg) && occursin("ego-specific", err.msg)
        twomode = network(4; bipartite=2)
        err = try as_rank_network(twomode); nothing catch e; e end
        @test err isa ArgumentError && occursin("two-mode", err.msg)

        # Rejected: an arc without a rank, an ego with an incomplete ranking —
        # the message names the ego (and the attribute)
        incomplete = rank_network_from(ref)
        rem_edge!(incomplete, 2, 4)
        err = try as_rank_network(incomplete); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin("ego 2", err.msg) && occursin("actor 4", err.msg) && occursin("COMPLETE", err.msg)
        duplicated = rank_network_from(ref)
        set_edge_attribute!(duplicated, :rank, 3, 1, ref.ranks[3, 2])   # ego 3 gives two alters one rank
        err = try as_rank_network(duplicated); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin("ego 3", err.msg) && occursin(":rank", err.msg) && occursin("permutation", err.msg)
        noninteger = rank_network_from(ref)
        set_edge_attribute!(noninteger, :rank, 1, 2, 1.5)
        err = try as_rank_network(noninteger); nothing catch e; e end
        @test err isa ArgumentError
        @test occursin("ego 1", err.msg) && occursin("not an integer", err.msg)
        # Integer-valued floats and other integer types convert
        floaty = rank_network_from(ref)
        set_edge_attribute!(floaty, :rank, 1, 2, Float64(ref.ranks[1, 2]))
        set_edge_attribute!(floaty, :rank, 1, 3, Int8(ref.ranks[1, 3]))
        @test rank_matrix(as_rank_network(floaty)) == rank_matrix(ref)
        # The matrix method is untouched by the Network method
        @test rank_matrix(as_rank_network(rank_matrix(ref))) == rank_matrix(ref)
    end

