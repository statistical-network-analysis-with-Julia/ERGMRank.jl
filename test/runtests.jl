    @testset "Every exported docstring carries a runnable example (criterion 5)" begin
        # Grade-A criterion 5: every export has a docstring with a runnable
        # example. The docs build (checkdocs=:exports) checks presence, not
        # content, so walk the docsystem: every ERGMRank-owned docstring of an
        # exported binding — including the ones ERGMRank attaches to the shared
        # Networks/StatsAPI generics (`gof`, `coeftable`, `objective`, ...) —
        # must contain a fenced ```julia block, and every such block must RUN
        # in a fresh module that has done nothing but `using ERGMRank` (so an
        # example that needs `Random` or `Networks` says so itself). Names
        # ERGMRank merely re-exports (`compute`, `coef`, `approximations`, ...)
        # are documented in Networks.jl/StatsAPI and only need to be
        # documented somewhere. Mirrors ERGM.jl's testset of the same name.
        meta_rank = Base.Docs.meta(ERGMRank)
        documented_elsewhere(b) = any(haskey(Base.Docs.meta(m), b)
                                      for m in (Networks, ERGM, StatsAPI))
        undocumented = String[]
        missing_example = String[]
        blocks = Tuple{String,String}[]
        for nm in names(ERGMRank)
            nm === :ERGMRank && continue
            b = Base.Docs.Binding(ERGMRank, nm)
            if !haskey(meta_rank, b)
                documented_elsewhere(b) || push!(undocumented, string(nm))
                continue
            end
            has_example = false
            for (_, ds) in meta_rank[b].docs
                txt = ds.text isa AbstractString ? ds.text : join(string.(ds.text), "\n")
                for m in eachmatch(r"```julia\n(.*?)```"s, txt)
                    has_example = true
                    push!(blocks, (string(nm), String(m.captures[1])))
                end
                occursin("```jldoctest", txt) && (has_example = true)
            end
            has_example || push!(missing_example, string(nm))
        end
        @test isempty(undocumented)
        @test isempty(missing_example)
        # ERGMRank-owned docstrings sit on the foreign generics it extends
        for nm in (:gof, :coeftable, :confint, :aic, :bic, :objective, :is_exact, :se_method)
            @test haskey(meta_rank, Base.Docs.Binding(ERGMRank, nm))
        end
        @test length(blocks) >= 28

        # A `# true` / `# false` comment on a top-level line is a CLAIM about
        # the value of that line, and it is asserted, the way a `@test` line
        # would be: `fit.converged   # true` on a separated fit used to run
        # fine while lying. The line's code is wrapped in a checker that
        # compares the value with the comment (`# true: ...` and `# true —
        # ...` count too); lines that are not a complete expression on their
        # own (a matrix literal's middle row) or are indented (inside a
        # for/try block) are left as they are.
        claim = r"^(\S.*?)\s+#\s*(true|false)(?:\s*[:—–-].*)?\s*$"
        function assert_claims(nm, code)
            lines = split(code, '\n')
            n_claims = 0
            for (k, line) in enumerate(lines)
                mm = match(claim, line)
                mm === nothing && continue
                expr_text, expected = String(mm.captures[1]), mm.captures[2]
                parsed = Meta.parse(expr_text; raise=false)
                parsed isa Expr && parsed.head in (:incomplete, :error) && continue
                lines[k] = "__doc_claim__(($expr_text), $expected, $(repr(expr_text)))"
                n_claims += 1
            end
            return join(lines, '\n'), n_claims
        end
        function __doc_claim__(value, expected::Bool, text::String)
            value === expected ||
                error("the docstring claims `$text   # $expected` but it is $(repr(value))")
            return value
        end

        n_claims_total = 0
        for (nm, code) in blocks
            m = Module(Symbol("DocExample_", nm))
            checked, n_claims = assert_claims(nm, code)
            n_claims_total += n_claims
            # stderr is captured: a docstring example must be silent (the one
            # exception is the deprecated `fit_rank_ergm`, whose example
            # demonstrates the binding deprecation warning)
            ok, captured = mktemp() do path, io
                ok = try
                    Core.eval(m, :(using ERGMRank))
                    Core.eval(m, :(const __doc_claim__ = $__doc_claim__))
                    Base.CoreLogging.with_logger(Base.CoreLogging.NullLogger()) do
                        redirect_stderr(io) do
                            Core.eval(m, Meta.parseall(checked; filename="docstring:$nm"))
                        end
                    end
                    true
                catch err
                    println(stdout, "docstring example of $nm failed: ", sprint(showerror, err))
                    false
                end
                flush(io)
                ok, read(path, String)
            end
            @test ok
            if nm == "fit_rank_ergm"
                @test occursin("fit_rank_ergm is deprecated", captured)
            else
                isempty(captured) || println(stdout, "docstring example of $nm wrote to stderr: ", captured)
                @test isempty(captured)
            end
        end
        # The claim checker engages on the `# true` lines the docstrings carry
        @test n_claims_total >= 40
        # ...and catches a false claim
        @test_throws ErrorException __doc_claim__(false, true, "1 == 2")
        bad, nb = assert_claims("x", "1 == 2   # true")
        @test nb == 1
        @test_throws ErrorException Core.eval(Module(:DocClaimCheck),
                                              quote
                                                  const __doc_claim__ = $__doc_claim__
                                                  $(Meta.parseall(bad))
                                              end)
    end

    # ------------------------------------------------------------------
    # Golden fixture: a REAL statnet `ergm.rank` fit on Newcomb's fraternity
    # ranks (issue #8). test/fixtures/r/newcomb_rank.R regenerates it (slow:
    # ~17 minutes — a rank-ERGM MCMLE takes ~3 min and the script does six).
    #
    # Two estimators, two kinds of assertion (finding N4, closed):
    #
    #   `method=:mcmle` IS ergm.rank's estimator (the MCMC MLE), run here at
    #   ergm.rank's own MCMC budget from the fixture's `mcmc_control`. Its
    #   coefficients are ASSERTED against `mle_coefficients` within
    #   `coefficient_sd_multiple` × (`mle_seed_sd` + `julia_seed_sd`) — the two
    #   implementations' seed-to-seed spreads, both frozen with provenance in
    #   the TOML — on two Julia seeds, and its standard errors within
    #   `std_errors_rtol` of `mle_std_errors` (both include the MCMC-error
    #   component). Do not raise either tolerance: the [tolerance] block
    #   records why 4 and 15 % are already generous.
    #
    #   `method=:mple` (the default) is a SWAP PSEUDO-LIKELIHOOD — a different
    #   estimator, not a noisy MLE — so its gap to the MLE is CHARACTERISED
    #   (systematic, small, anticonservative SEs), never tolerated.
    # ------------------------------------------------------------------
    @testset "Golden fixture: statnet ergm.rank on newcomb (MCMLE asserted, swap-MPLE characterised)" begin
        g = load_golden(joinpath(@__DIR__, "fixtures", "newcomb_rank.toml"))
        @test g.provenance["ergm_rank_version"] == "4.1.2"

        n = Int(g.values["n_actors"])
        M = zeros(Int, n, n)
        for i in 1:n, j in 1:n
            M[i, j] = Int(g.values["ranks"][i][j])
        end
        rnet = RankNetwork(M)
        @test is_valid_ranking(rnet)

        terms = [RankDeference(), RankNonconformity(:all)]

        # --- ASSERTED: the observed sufficient statistics ---------------------
        # A deterministic function of the ranking — no estimator, no Monte Carlo.
        # Machine precision, and a disagreement is a bug in a term formula. (The
        # term values were already golden-tested against ergm.rank 4.1.2 from
        # literals in a comment; this re-pins them from a provenanced file.)
        @test g.values["summary_statistic_names"] == ["deference", "nonconformity"]
        stats = [compute(t, rnet) for t in terms]
        @test check_golden(g, "summary_statistics", stats) ||
              error(golden_report(g, "summary_statistics", stats))

        r_coef = Float64.(g.values["mle_coefficients"])
        r_se = Float64.(g.values["mle_std_errors"])
        r_sd = Float64.(g.values["mle_seed_sd"])

        # --- ASSERTED: method=:mcmle reproduces ergm.rank's MCMC MLE ---------
        # ergm.rank's own budget, read from the fixture's provenance:
        # control.ergm(MCMC.samplesize=2048, MCMC.burnin=8192, MCMC.interval=512)
        ctl = g.provenance["mcmc_control"]
        budget(key) = parse(Int, match(Regex(key * "=(\\d+)"), ctl).captures[1])
        n_samples, burnin, interval = budget("samplesize"), budget("burnin"), budget("interval")
        @test (n_samples, burnin, interval) == (2048, 8192, 512)
        julia_sd = Float64.(g.tolerance["julia_seed_sd"])
        multiple = Float64(g.tolerance["coefficient_sd_multiple"])
        se_rtol = Float64(g.tolerance["std_errors_rtol"])
        @test multiple == 4 && se_rtol == 0.15
        # The frozen Julia spread is the same order as R's (a sanity check on
        # the provenance, not a tolerance): neither implementation is noisier
        # than the other by more than a factor of 2
        @test all(0.5 .< julia_sd ./ r_sd .< 2.0)
        atol = multiple .* (r_sd .+ julia_sd)

        # --- ASSERTED: the bridge log-likelihood, under R's convention --------
        # ergm.rank's logLik is RELATIVE to the uniform-ordering model θ = 0
        # (ergm defines a valued ERGM's null likelihood as 0); ERGMRank reports
        # the ABSOLUTE log-likelihood, log Z(0) = n·log((n−1)!) exact. The two
        # bridges agree within their Monte-Carlo errors (both frozen in the
        # fixture: R's own MC standard error, Julia's seed-to-seed sd).
        r_ll = Float64(g.values["mle_loglik"])
        r_ll_se = Float64(g.values["mle_loglik_mc_se"])
        julia_bridge_sd = Float64(g.tolerance["julia_bridge_sd"])
        ll_multiple = Float64(g.tolerance["loglik_sd_multiple"])
        @test ll_multiple == 4
        @test 0.005 < julia_bridge_sd < 0.05 && 0 < r_ll_se < 0.5
        ll_atol = ll_multiple * (r_ll_se + julia_bridge_sd)
        logZ0 = ERGMRank._log_n_orderings(n)
        @test logZ0 ≈ n * log(factorial(big(n - 1))) atol = 1e-9
        @test Int(g.values["mle_nobs"]) == n * (n - 1) == 272        # R's nobs.ergm
        @test Int(g.values["mle_df"]) == length(terms)

        # Two Julia seeds. The bridge runs on the first (16 rungs of 512
        # draws each at the fit's burn-in and interval) and is skipped on the
        # second: it runs after the final sample and cannot touch the
        # coefficients or the standard errors (pinned by the reproducibility
        # testset).
        for (seed, rungs) in ((1, 16), (2, 0))
            mle = fit_ergm_rank(rnet, terms; method=:mcmle, n_samples=n_samples,
                                burnin=burnin, interval=interval, bridge_rungs=rungs,
                                bridge_samples=512, rng=Random.Xoshiro(seed))
            @test mle.converged
            @test mle.method === :mcmle
            @test fit_metadata(mle).objective == :likelihood
            @test check_statsapi(mle; strict=true) !== nothing
            @test nobs(mle) == mle.n_kept == Int(g.values["mle_nobs"])
            @test dof(mle) == Int(g.values["mle_df"])
            if rungs == 0
                @test isnan(loglikelihood(mle)) && isnan(aic(mle)) && isnan(bic(mle))
            else
                rel = loglikelihood(mle) + logZ0                   # R's convention
                @test abs(rel - r_ll) <= ll_atol ||
                      error("seed $seed: bridge log-likelihood $(loglikelihood(mle)) " *
                            "+ log Z(0) = $rel vs ergm.rank's logLik $r_ll (atol " *
                            "$ll_atol = $ll_multiple × (mle_loglik_mc_se + julia_bridge_sd))")
                # The absolute value sits 17·log(16!) ≈ 521 below R's number:
                # the offset the docs state, and a user comparing AIC with R sees
                @test loglikelihood(mle) < r_ll - 500
                @test logZ0 ≈ 17 * log(factorial(big(16))) atol = 1e-9
                # AIC/BIC: R's, shifted by −2·log Z(0); BIC on the same nobs
                @test abs((aic(mle) - 2 * logZ0) - Float64(g.values["mle_aic"])) <= 2 * ll_atol
                @test abs((bic(mle) - 2 * logZ0) - Float64(g.values["mle_bic"])) <= 2 * ll_atol
                @test bic(mle) == -2 * loglikelihood(mle) + dof(mle) * log(272)
            end
            @test all(abs.(coef(mle) .- r_coef) .<= atol) ||
                  error("seed $seed: MCMLE $(coef(mle)) vs ergm.rank $r_coef " *
                        "(atol $atol = $multiple × (mle_seed_sd + julia_seed_sd))")
            # ...and it is the SAME estimator: the gap is inside the
            # Monte-Carlo band the swap-MPLE gap (below) sits 16× outside of
            @test all(abs.(coef(mle) .- r_coef) .< 5 .* r_sd)
            @test all(abs.(stderror(mle) .- r_se) .<= se_rtol .* r_se) ||
                  error("seed $seed: MCMLE SEs $(stderror(mle)) vs ergm.rank $r_se " *
                        "(rtol $se_rtol)")
            @test all(isfinite, stderror(mle))
            @test all(diag(mle.vcov) .>= diag(mle.vcov_fisher))
        end

        # --- ASSERTED: the CHARACTER of the swap-MPLE's gap -------------------
        fit = fit_ergm_rank(rnet, terms)
        @test fit.method === :mple
        @test fit.converged
        @test check_statsapi(fit; strict=true) !== nothing
        gap = abs.(fit.coefficients .- r_coef)

        # The swap-MPLE is a different estimator, so its gap to the MLE is not
        # tolerated but characterised. Observed as of ergm.rank 4.1.2:
        #   swap-MPLE : [-0.14091, -0.0058538]
        #   ergm.rank : [-0.15310, -0.0065927]
        # Two things are true at once and both matter:
        #
        # (1) The gap is SYSTEMATIC, not Monte-Carlo. ergm.rank's own seed-to-seed
        #     sd on these coefficients is 7.4e-4 and 5.6e-5; the gap is 1.2e-2 and
        #     7.4e-4 — 16x and 13x that width. No amount of MCMC would close it.
        #     The two estimators genuinely disagree.
        @test all(gap .> 5 .* r_sd)
        #
        # (2) But the disagreement is SMALL on the scale that matters: 0.30 and
        #     0.43 of an ergm.rank standard error. Same sign, same order, same
        #     substantive story. The swap-MPLE is a different estimator, not a
        #     broken one — and that is exactly the claim the package makes.
        @test all(gap .< 0.6 .* r_se)

        # --- ASSERTED: the pseudo-Hessian SEs are anticonservative, measurably --
        # The package documents this; here is the number. Against ergm.rank's MLE
        # standard errors, the inverse pseudo-Hessian understates by ~3.9x
        # (deference) and ~2.0x (nonconformity) — the overlapping swap comparisons
        # are being multiplied as if independent.
        @test all(fit.std_errors .< r_se)
        @test r_se[1] / fit.std_errors[1] > 2.0

        # ...and `se=:bootstrap` — the honest option — moves most of the way back.
        # Bootstrap: [0.0280, 0.00192] against R's [0.0404, 0.00174]. Still not
        # the MLE's, because it is bootstrapping a different estimator, but no
        # longer understating by a factor of four.
        boot = fit_ergm_rank(rnet, terms; se=:bootstrap, n_boot=60,
                             rng=Random.Xoshiro(7))
        @test boot.coefficients ≈ fit.coefficients atol = 1e-12   # point est unchanged
        @test all(boot.std_errors .> fit.std_errors)
        @test abs(boot.std_errors[1] - r_se[1]) < abs(fit.std_errors[1] - r_se[1])
        @test all(isfinite, boot.boot_replicates)                # no exclusions here
    end
