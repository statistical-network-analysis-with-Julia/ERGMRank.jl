# The 4-actor test network validated against R ergm.rank 4.1.2
# (higher rank value = higher standing)
function r_test_network()
    m = zeros(Int, 4, 4)
    m[1, 2] = 3; m[1, 3] = 2; m[1, 4] = 1
    m[2, 1] = 3; m[2, 3] = 1; m[2, 4] = 2
    m[3, 1] = 1; m[3, 2] = 3; m[3, 4] = 2
    m[4, 1] = 2; m[4, 2] = 1; m[4, 3] = 3
    return RankNetwork(m)
end

# Random valid rank network: each ego's ranks are a random permutation
function random_rank_network(n; rng=Random.default_rng())
    m = zeros(Int, n, n)
    for i in 1:n
        perm = randperm(rng, n - 1)
        c = 0
        for j in 1:n
            i == j && continue
            c += 1
            m[i, j] = perm[c]
        end
    end
    return RankNetwork(m)
end

# Evaluate `expr` (in Main) while capturing stderr: the deprecated binding
# `fit_rank_ergm` prints Julia's C-level binding deprecation warning there
# (Pkg.test runs with --depwarn=yes), which no logger sees. Returns
# `(value, captured_stderr)`.
function deprecated_access(expr)
    return mktemp() do path, io
        value = redirect_stderr(io) do
            Core.eval(Main, expr)
        end
        flush(io)
        value, read(path, String)
    end
end

