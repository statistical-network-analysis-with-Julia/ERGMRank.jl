    # The shared optimizer's verdict on the swap design is scale-free
    # (`Networks.newton_fit` converges on the Newton decrement ½∇ℓ'(−H)⁻¹∇ℓ
    # beside the gradient norm). On the 2,040-row Newcomb design, whose
    # Hessian entries are in the thousands, Newton used to stall AT the
    # maximum with ‖∇ℓ‖ ≈ 5e-4 and report `converged = false`, and BLAS
    # rounding then decided which bootstrap replicates counted as converged
    # (1 or 3 of 60 depending on the thread count); ERGMRank carried a
    # `_stalled_at_optimum` shim for it. The shim is gone; this pins the
    # verdict the kernel now gives directly.
    # ------------------------------------------------------------------
    @testset "newton_fit converges on the swap design without a local shim" begin
        rnet = newcomb_week1()
        terms = AbstractERGMTerm[RankDeference(), RankNonconformity(:all)]
        D = ERGMRank._rank_design(terms, copy(rnet))
        m = size(D, 1)
        derivatives = Networks.logistic_derivatives(D, trues(m))
        fit = Networks.newton_fit(derivatives, zeros(2); maxiter=100, tol=1e-8)
        @test fit.converged
        _, g, H = derivatives(fit.θ)
        # ... at the maximum: the remaining Newton decrement is far below tol
        @test 0 <= 0.5 * dot(g, -(H \ g)) < 1e-8
        @test norm(g) < 1e-3
        r = ERGMRank._rank_mple_fit(terms, rnet)
        @test r.converged
        @test r.grad_norm < 1e-3
        @test !isdefined(ERGMRank, :_stalled_at_optimum)
    end

