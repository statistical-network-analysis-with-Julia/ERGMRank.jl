    # ------------------------------------------------------------------
    # Item 28: the AlterSwap sampler runs on the ONE Metropolis kernel,
    # `ERGM.mh_toggle!`, with the swap `(ego, j, k)` as the move. Two things
    # are pinned: the sampled sequence is bit-identical to the hand-written
    # loop the kernel replaced (same rng consumption order), and a step
    # allocates nothing (the change statistics are written into the kernel's
    # `delta` workspace by `_swap_delta!` over a term tuple).
    # ------------------------------------------------------------------
    @testset "AlterSwap sampler runs on ERGM.mh_toggle!" begin
        terms = AbstractERGMTerm[RankDeference(), RankNonconformity()]
        θ = [-0.3, 0.05]
        start = random_rank_network(6; rng=Xoshiro(21))
        burnin, interval, n_sim = 150, 7, 12

        # The pre-kernel loop, verbatim, as the reference sequence
        function old_loop(rnet, terms, θ; n_sim, burnin, interval, rng)
            current = copy(rnet)
            n = current.n
            draws = RankNetwork[]
            for step in 1:(burnin + n_sim * interval)
                ego = rand(rng, 1:n)
                j = rand(rng, 1:n)
                while j == ego
                    j = rand(rng, 1:n)
                end
                k = rand(rng, 1:n)
                while k == ego || k == j
                    k = rand(rng, 1:n)
                end
                delta = ERGMRank._swap_delta_bruteforce(terms, current, ego, j, k)
                if log(rand(rng)) < dot(θ, delta)
                    swap_ranks!(current, ego, j, k)
                end
                if step > burnin && (step - burnin) % interval == 0
                    push!(draws, copy(current))
                end
            end
            return draws
        end

        new_draws = simulate_rank_ergm(start, terms, θ; n_sim=n_sim, burnin=burnin,
                                       interval=interval, rng=Xoshiro(5))
        old_draws = old_loop(start, terms, θ; n_sim=n_sim, burnin=burnin,
                             interval=interval, rng=Xoshiro(5))
        @test length(new_draws) == n_sim
        @test all(rank_matrix(a) == rank_matrix(b) for (a, b) in zip(new_draws, old_draws))
        @test all(is_valid_ranking, new_draws)

        # A step allocates nothing: doubling the burn-in adds 0 bytes
        function sampler_allocs(B)
            simulate_rank_ergm(start, terms, θ; n_sim=1, burnin=B, interval=1,
                               rng=Xoshiro(1))                        # warm up
            return @allocated simulate_rank_ergm(start, terms, θ; n_sim=1, burnin=B,
                                                 interval=1, rng=Xoshiro(1))
        end
        a1 = sampler_allocs(1_000)
        a2 = sampler_allocs(2_000)
        @test a2 == a1

        # `_swap_delta!` itself: 0 bytes on a term tuple (measured inside a
        # function, where the tuple's type is inferred as it is in the sampler)
        work = copy(start)
        delta = zeros(2)
        ts = Tuple(terms)
        delta_allocs(delta, ts, work) =
            @allocated ERGMRank._swap_delta!(delta, ts, work, 1, 2, 3)
        delta_allocs(delta, ts, work)                 # warm up
        @test delta_allocs(delta, ts, work) == 0
        @test delta == ERGMRank._swap_delta(terms, work, 1, 2, 3)
        @test rank_matrix(work) == rank_matrix(start)   # restored
    end

