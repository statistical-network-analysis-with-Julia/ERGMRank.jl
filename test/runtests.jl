        r = 0
        work = copy(rnet)
        for ego in 1:n, j in 1:n, k in (j + 1):n
            (j == ego || k == ego) && continue
            r += 1
            D_brute[r, :] = -ERGMRank._swap_delta_bruteforce(terms, work, ego, j, k)
        end
        @test r == m
        D = ERGMRank._rank_design(terms, copy(rnet))
        @test size(D) == (m, p)
        @test D == D_brute

