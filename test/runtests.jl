        @test fz.n_kept == 6
        @test count(iszero, ERGMRank._rank_design(fz.model.terms, copy(zero))) == 6
        @test loglikelihood(fz) ≈ fz.n_kept * log(0.5)
        @test loglikelihood(fz) ≈ -4.1589 atol = 1e-4
        @test aic(fz) ≈ -2 * fz.n_kept * log(0.5)          # dof 0
